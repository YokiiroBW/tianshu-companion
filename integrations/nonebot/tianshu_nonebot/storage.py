"""NoneBot-owned SQL schema/import; paths remain local even when SQL is remote."""

import re
from contextlib import closing
from contextlib import suppress
import sqlite3
import hashlib
import json
import uuid

from tianshu_storage import MemoryCursor, StorageOptions, StorageRuntime


def dialect(connection, sql, parameters):
    if ";" in sql.strip().rstrip(";"):
        if parameters:
            raise ValueError("Script parameters are unsupported")
        result = MemoryCursor()
        for statement in sql.split(";"):
            if statement.strip():
                result = connection.execute(statement)
        return result
    text = sql.strip().rstrip(";")
    if text.upper() == "PRAGMA USER_VERSION":
        return MemoryCursor([(1,)], columns=["user_version"])
    if text.upper().startswith(
        ("PRAGMA USER_VERSION=", "PRAGMA JOURNAL_MODE", "PRAGMA SYNCHRONOUS", "PRAGMA BUSY_TIMEOUT")
    ):
        return MemoryCursor()
    if text.upper() == "BEGIN IMMEDIATE":
        result = connection.native("BEGIN")
        connection.native("SELECT pg_advisory_xact_lock(hashtextextended(current_schema(),233))")
        return result
    native = re.sub(r"\bREAL\b", "DOUBLE PRECISION", sql, flags=re.I)
    if text.upper().startswith("CREATE TABLE"):
        native = re.sub(r"\bINTEGER\b", "BIGINT", native, flags=re.I)
        native = re.sub(r"\bTEXT\b", 'TEXT COLLATE "C"', native, flags=re.I)
    native = native.replace(
        "json_set(receipt,'$.state','unknown')",
        "jsonb_set(receipt::jsonb,'{state}','\"unknown\"'::jsonb)::text",
    )
    native = native.replace("json_extract(receipt,'$.state')", "(receipt::jsonb->>'state')")
    if "INSERT OR IGNORE INTO" in native:
        native = native.replace("INSERT OR IGNORE INTO", "INSERT INTO") + " ON CONFLICT DO NOTHING"
    return connection.native(native, parameters) if native != sql else None


def open_database(path, logical_name, schema_sql, tables, *, settings=None, ordered=(), owner=True):
    runtime = StorageRuntime(
        StorageOptions.from_settings(settings or {}),
        service="nonebot",
        state_directory=str(path) + ".storage",
    )

    def prepare(connection, source):
        state = connection.native(
            "SELECT state FROM __tianshu_storage_binding WHERE singleton=1"
        ).fetchone()
        if state is None or state[0] not in {"initializing", "ready"}:
            raise RuntimeError("NoneBot PostgreSQL binding state invalid")
        if state[0] == "ready":
            actual = {
                row[0]
                for row in connection.native(
                    "SELECT tablename FROM pg_catalog.pg_tables WHERE schemaname=current_schema()"
                )
            }
            required = set(tables) | {"nonebot_schema"}
            if not required <= actual:
                raise RuntimeError("NoneBot PostgreSQL tables missing")
            version = connection.native("SELECT version FROM nonebot_schema").fetchone()
            if version is None or version[0] != 1 or source is not None:
                raise RuntimeError("Unsupported NoneBot target schema")
            return
        if (
            source is not None
            and logical_name == "journal"
            and source.execute("PRAGMA user_version").fetchone()[0] not in (0, 1)
        ):
            raise RuntimeError("Unsupported NoneBot journal source schema")
        connection.native("CREATE TABLE IF NOT EXISTS nonebot_schema(version INTEGER NOT NULL)")
        version = connection.native("SELECT version FROM nonebot_schema").fetchone()
        if version is not None:
            if version[0] != 1 or source is not None:
                raise RuntimeError("Unsupported NoneBot target schema")
            return
        connection.executescript(schema_sql)
        for table in ordered:
            connection.native(
                f"ALTER TABLE {table} ADD COLUMN rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE"
            )
        if source is not None:
            for table in tables:
                info = source.execute(f"PRAGMA table_info({table})").fetchall()
                columns = [row[1] for row in info]
                if not columns:
                    continue
                if table in ordered:
                    columns.append("rowid")
                names = ",".join(columns)
                count = 0
                checksum = hashlib.sha256()
                keys = [row[1] for row in sorted(info, key=lambda row: row[5]) if row[5]]
                order = "rowid" if table in ordered else ",".join(keys)
                for row in source.execute(f"SELECT {names} FROM {table} ORDER BY {order}"):
                    connection.native(
                        f"INSERT INTO {table}({names}) VALUES({','.join('?' for _ in columns)})",
                        tuple(row),
                    )
                    checksum.update(
                        json.dumps(
                            list(row), ensure_ascii=False, allow_nan=False, separators=(",", ":")
                        ).encode()
                    )
                    checksum.update(b"\n")
                    count += 1
                actual, found = hashlib.sha256(), 0
                with connection.raw.cursor(name="ts233_verify_" + uuid.uuid4().hex) as cursor:
                    cursor.itersize = 64
                    cursor.execute(f"SELECT {names} FROM {table} ORDER BY {order}")
                    for row in cursor:
                        actual.update(
                            json.dumps(
                                list(row),
                                ensure_ascii=False,
                                allow_nan=False,
                                separators=(",", ":"),
                            ).encode()
                        )
                        actual.update(b"\n")
                        found += 1
                if found != count or actual.digest() != checksum.digest():
                    raise RuntimeError("NoneBot migration field verification failed")
                if table in ordered:
                    connection.native(
                        f"SELECT setval(pg_get_serial_sequence('{table}','rowid'),GREATEST(COALESCE((SELECT MAX(rowid) FROM {table}),0)+1,1),false)"
                    )
        connection.native("INSERT INTO nonebot_schema VALUES(1)")

    db = None
    try:
        runtime.start()
        database = runtime.database(logical_name, path, prepare=prepare, dialect=dialect)
        db = database.connect(isolation_level=None, check_same_thread=False)
        if owner and database.backend == "postgresql":
            acquired = db.native(
                "SELECT pg_try_advisory_lock(hashtextextended(current_schema(),23300))"
            ).fetchone()[0]
            if not acquired:
                raise RuntimeError("Database already has a running owner")
        runtime.finalize()
        return runtime, db
    except BaseException:
        if db is not None:
            close_database(runtime, db)
        else:
            runtime.close()
        raise


def close_database(runtime, db):
    try:
        if runtime.backend == "postgresql":
            with suppress(sqlite3.Error):
                db.native("SELECT pg_advisory_unlock(hashtextextended(current_schema(),23300))")
    finally:
        try:
            with suppress(sqlite3.Error):
                db.close()
        finally:
            runtime.close()


def read_access_key(path, settings=None):
    with closing(
        StorageRuntime.open_existing(
            StorageOptions.from_settings(settings or {}),
            service="nonebot",
            state_directory=str(path) + ".storage",
            name="rpc",
            path=path,
        )
    ) as db:
        row = db.execute("SELECT value FROM meta WHERE key='access_key'").fetchone()
        if row is None:
            raise ValueError("Adapter has not initialized")
        return row[0]
